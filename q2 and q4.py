import timeit

def compare_lookup(n):
    vehicle_dict = {f"V{i:06d}": i for i in range(n)}
    vehicle_list = list(vehicle_dict.items())
    target = f"V{n-1:06d}"

    def dictionary_search():
        return vehicle_dict.get(target)

    def linear_search():
        for key, value in vehicle_list:
            if key == target:
                return value
        return None

    dict_time = timeit.timeit(dictionary_search, number=10000)
    list_time = timeit.timeit(linear_search, number=100)

    print(f"Dataset: {n} vehicles")
    print(f"Dictionary: {dict_time / 10000 * 1e6:.3f} microseconds")
    print(f"List: {list_time / 100 * 1e6:.3f} microseconds")
    print()

