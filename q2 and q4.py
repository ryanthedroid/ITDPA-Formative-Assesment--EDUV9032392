# BINARY SEARCH TREE IMPLEMENTATION
class Node:
    def __init__(self, name):
        self.name = name
        self.left = None
        self.right = None

class BST:
    def __init__(self):
        self.root = None

    def add(self, name):
        def insert(node, name):
            if node is None:
                return Node(name)
            if name < node.name:
                node.left = insert(node.left, name)
            elif name > node.name:
                node.right = insert(node.right, name)
            return node

        self.root = insert(self.root, name)

    def find(self, name):
        current = self.root
        while current is not None:
            if name == current.name:
                return True
            if name < current.name:
                current = current.left
            else:
                current = current.right
        return False

tree = BST()

for suburb in suburbs:
    tree.add(suburb)

tree.add("Newlands")

print("\nBinary search tree")
print("Added Newlands:", tree.find("Newlands"))
print("Find Parow:", tree.find("Parow"))
print("Find Atlantis:", tree.find("Atlantis"))

