import heapq

class IncidentQueue:
    def __init__(self):
        self.heap = []
        self.counter = 0

    def add(self, name, severity):
        if severity not in ("critical", "routine"):
            raise ValueError("Invalid severity: The severity must be either critical or routine")

        priority = 0 if severity == "critical" else 1
        heapq.heappush(self.heap, (priority, self.counter, name))
        self.counter += 1

    def dispatch(self):
        if not self.heap:
            return "No incidents waiting"

        priority, order, name = heapq.heappop(self.heap)
        severity = "critical" if priority == 0 else "routine"
        return f"{name} ({severity})"


